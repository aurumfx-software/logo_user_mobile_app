export const featuredBusinesses = businesses.filter(b => b.isFeatured);
export const nearbyBusinesses = businesses.filter(b => parseFloat(b.distance) <= 1.0);

export const getBusinessesByCategory = (categorySlug) => {
  return businesses.filter(b => b.category === categorySlug);
};

export const getBusinessById = (id) => {
  return businesses.find(b => b.id === id);
};

export const searchBusinesses = (query) => {
  const q = query.toLowerCase();
  return businesses.filter(
    b =>
      b.name.toLowerCase().includes(q) ||
      b.category.toLowerCase().includes(q) ||
      b.tags.some(t => t.toLowerCase().includes(q)) ||
      b.description.toLowerCase().includes(q)
  );
};
